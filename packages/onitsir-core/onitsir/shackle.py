"""ONITSIR · Shackle v2 — the unified Governor layer.

This module fuses THREE independent SHACKLE implementations found across the
Fame510 portfolio into ONE canonical governance surface (see architecture
doc section 1, "Same governance concept, three implementations"):

  - ONITSIR/onitsir/shackle.py        -> pure decide() + hash-chained AuditLedger
  - ADROS/backend/cognitive/shackle.py -> declarative JSON-rule veto engine
  - AgentOmega/app/shackle.py          -> DenyReason/HitlMode enums, bounded-wait
                                          HITL semantics, Ed25519-signed ledger

SYNERGY #3 (Port Shackle Governor as agentosirus's policy gate): `decide()`
and `Governor` here are the SINGLE canonical implementation; agentosirus's
`onitsirClient.ts` calls `POST /api/mission/:id/gate` (wrapping
`Governor.evaluate()`) rather than re-implementing any of this in TypeScript.

SYNERGY #6 (Single governance source of truth): `Verdict`/`DenyReason`/
`HitlMode` are enums here; `agentosirus-web/src/lib/shackle.ts` mirrors their
*string values only*, generated by `infra/scripts/sync-shackle-types.mjs`
from this module — never re-implementing `decide()`.

SYNERGY #9 (Ed25519 signing / audit ledger upgrade): `AuditLedger` gains
optional Ed25519 signing, ported from AgentOmega's `AuditLedger`.

SYNERGY #10 (Bounded-timeout HITL): `HitlMode` enum + `Governor.await_hitl()`
bounded-wait resolution logic, ported from AgentOmega's `_await_hitl()` /
`ShackleGovernor`. A HITL that never gets an operator response ALWAYS
resolves to safe DENY on timeout — it can never hang forever.

SYNERGY #11 (Declarative JSON-rule veto layer): `Governor.evaluate()` calls a
`ShackleValidator` (ported from ADROS in `shackle_rules.py`) as an
additional hard-veto check before returning ALLOW.

SYNERGY #12 (Additive ethics tag-weight scoring): `Governor.evaluate()`
accepts `tags` and additively scores them via `EthicsEngine` (ported from
ADROS in `ethics.py`); a below-threshold score forces DENY.

Shackle sits IN FRONT OF the Iron-Law verification gate:

    goal -> route -> [ Shackle: may this run? ] -> run -> [ Iron Law: did it pass? ] -> ship
"""
